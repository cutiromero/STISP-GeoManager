import { DeleteOutlined } from "@ant-design/icons";
import { Alert, App, Button, Checkbox, Modal, Space, Spin, Typography } from "antd";
import { useEffect, useState } from "react";
import { agentApi } from "../api/agent";
import type { AgentConversation, AgentConversationDeletionPreview } from "../api/generated/types.gen";
import { useComputeText } from "../compute/ui";

function storageSize(bytes: number) {
  if (bytes < 1024 ** 2) return `${(bytes / 1024).toFixed(1)} KiB`;
  if (bytes < 1024 ** 3) return `${(bytes / 1024 ** 2).toFixed(1)} MiB`;
  return `${(bytes / 1024 ** 3).toFixed(2)} GiB`;
}

export default function ConversationDeleteButton({ conversation, onDeleted, onError }: {
  conversation: AgentConversation;
  onDeleted: () => void | Promise<void>;
  onError: (error: unknown) => void;
}) {
  const ui = useComputeText();
  const { message } = App.useApp();
  const [open, setOpen] = useState(false);
  const [deleteData, setDeleteData] = useState(false);
  const [pending, setPending] = useState(false);
  const [preview, setPreview] = useState<AgentConversationDeletionPreview | null>(null);
  const [previewError, setPreviewError] = useState(false);

  useEffect(() => {
    if (!open) return;
    const controller = new AbortController();
    setPreview(null);
    setPreviewError(false);
    setDeleteData(false);
    void agentApi.deletionPreview(conversation.id, { signal: controller.signal })
      .then((value) => { if (!controller.signal.aborted) setPreview(value); })
      .catch(() => { if (!controller.signal.aborted) setPreviewError(true); });
    return () => controller.abort();
  }, [open, conversation.id]);

  const remove = async () => {
    if (pending || (deleteData && !preview)) return;
    setPending(true);
    try {
      const result = await agentApi.remove(conversation.id, deleteData && preview ? {
        deleteGeneratedData: true, confirmationToken: preview.confirmationToken,
      } : undefined);
      setOpen(false);
      const cleanup = result.cleanup;
      if (cleanup) {
        const text = ui(
          `已删除会话，清理 ${cleanup.deletedResources} 项入库成果、${cleanup.deletedOutputs} 份计算文件；保留 ${cleanup.retainedResources + cleanup.retainedOutputs} 项关联数据`,
          `Conversation deleted; removed ${cleanup.deletedResources} datasets and ${cleanup.deletedOutputs} output files; retained ${cleanup.retainedResources + cleanup.retainedOutputs} referenced items`,
        );
        if (cleanup.failedItems) message.warning(`${text}；${ui(`另有 ${cleanup.failedItems} 项清理失败`, `${cleanup.failedItems} items could not be removed`)}`);
        else message.success(text);
      }
      await onDeleted();
    } catch (error) {
      onError(error);
    } finally {
      setPending(false);
    }
  };

  return <>
    <Button size="small" type="text" danger aria-label={ui("删除", "Delete")} icon={<DeleteOutlined />} onClick={() => setOpen(true)} />
    {open && <Modal open title={ui("删除会话", "Delete conversation")}
      onCancel={() => { if (!pending) setOpen(false); }} onOk={() => void remove()}
      confirmLoading={pending} okText={ui("确认删除", "Delete")} cancelText={ui("取消", "Cancel")}
      okButtonProps={{ danger: true }} cancelButtonProps={{ disabled: pending }} closable={!pending} mask={{ closable: !pending }}>
      <Space orientation="vertical" size={16} style={{ width: "100%" }}>
        <Typography.Paragraph>{ui(`将删除“${conversation.title}”及其分析记录。`, `Delete “${conversation.title}” and its analysis history.`)}</Typography.Paragraph>
        <Checkbox checked={deleteData} disabled={!preview || pending || !(preview.resourceCount || preview.outputCount)} onChange={(event) => setDeleteData(event.target.checked)}>
          {ui("同时删除该对话任务产生的数据", "Also delete data generated by this conversation's tasks")}
        </Checkbox>
        {!preview && !previewError && <Spin size="small" />}
        {preview && <Typography.Text type="secondary">
          {ui(`可清理 ${preview.resourceCount} 项入库成果、${preview.outputCount} 份计算文件，预计 ${storageSize(preview.estimatedBytes)}。`, `${preview.resourceCount} datasets and ${preview.outputCount} output files can be removed (approximately ${storageSize(preview.estimatedBytes)}).`)}
          {!!preview.retainedCount && ui(`另有 ${preview.retainedCount} 项成果因引用或权限保留。`, ` ${preview.retainedCount} datasets are retained due to references or permissions.`)}
        </Typography.Text>}
        {previewError && <Alert type="warning" showIcon title={ui("关联数据检查失败，可以仅删除会话；重新打开此窗口可重试。", "Data check failed. You can delete the conversation only, or reopen this dialog to retry.")} />}
        <Typography.Text type="secondary">{ui("原始输入资料和其他任务、已保存工程仍在使用的数据会保留。勾选后清理的数据无法恢复。", "Original inputs and data used by other tasks or saved projects are retained. Removed generated data cannot be recovered.")}</Typography.Text>
      </Space>
    </Modal>}
  </>;
}
